package dev.martianzoo.tfm.tools

import dev.martianzoo.pets.ast.ClassName.Companion.cn
import dev.martianzoo.tfm.canon.Canon
import dev.martianzoo.tfm.canon.TfmCatalog
import dev.martianzoo.tfm.fake.FakeCanon
import java.io.File

/** Refreshes the checked-in test vocabulary from the catalogs, including global events. */
public fun main(args: Array<String>) {
  require(args.size == 1) { "Usage: generateCardNameConstants <output-file>" }
  val catalog = TfmCatalog(Canon, FakeCanon)
  val table = catalog.classTable
  val events = table.allSubclasses(table.getClass(cn("GlobalEvent"))).filterNot { it.abstract }
  val names = (catalog.cards + events).map { it.className.toString() }.sortedBy { it.lowercase() }
  File(args.single())
      .writeText(
          buildString {
            appendLine("// Generated by ./gradlew :tools:generateCardNameConstants. Do not edit.")
            appendLine("package dev.martianzoo.tfm.tests.cards.cardnames")
            appendLine()
            appendLine("import dev.martianzoo.pets.ast.ClassName")
            appendLine("import dev.martianzoo.pets.ast.ClassName.Companion.cn")
            appendLine()
            names.forEach { name ->
              appendLine("public val $name: ClassName = cn(\"$name\")")
            }
          }
      )
}
